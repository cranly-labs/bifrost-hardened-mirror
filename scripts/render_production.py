#!/usr/bin/env python3
"""Render the immutable production deployment manifest from the Coolify template."""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

DIGEST_REFERENCE = re.compile(r"^[a-z0-9][a-z0-9._/-]*@sha256:[0-9a-f]{64}$")

PRODUCTION_README = """# Production deployment branch

This branch is generated by the release workflow. It is intentionally small and
contains only the artifacts Coolify needs to deploy a verified Bifrost image.

- `compose.yaml` pins an immutable image digest.
- `release.json` records the upstream release, distribution version, and digest.

Do not edit this branch by hand. Changes are overwritten by the next successful
release. The source of truth is the `main` branch.
"""


def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--template", default="deploy/coolify/compose.yaml")
    parser.add_argument("--image", required=True, help="Immutable image reference")
    parser.add_argument("--version", required=True, help="Distribution version, for example v2.4.0")
    parser.add_argument("--upstream-tag", default="")
    parser.add_argument("--upstream-commit", default="")
    parser.add_argument("--output-dir", default="dist/production")
    parser.add_argument("--allow-tag", action="store_true", help="Permit a mutable tag instead of a digest")
    args = parser.parse_args(argv)

    if not args.allow_tag and not DIGEST_REFERENCE.match(args.image):
        print(
            "error: production images must be pinned by digest "
            "(ghcr.io/owner/repo@sha256:<64 hex characters>)",
            file=sys.stderr,
        )
        return 1

    root = Path(args.root).resolve()
    template_path = root / args.template
    if not template_path.exists():
        print(f"error: template not found: {template_path}", file=sys.stderr)
        return 1

    rendered = template_path.read_text(encoding="utf-8")
    replacements = {
        "{{IMAGE}}": args.image,
        "${BIFROST_IMAGE:?BIFROST_IMAGE must pin an immutable image reference}": args.image,
        "{{VERSION}}": args.version,
        "{{UPSTREAM_TAG}}": args.upstream_tag or "unknown",
        "{{UPSTREAM_COMMIT}}": args.upstream_commit or "unknown",
        "{{RELEASED_AT}}": utc_now(),
        "{{DIGEST}}": args.image.split("@", 1)[1] if "@" in args.image else "tag",
    }
    for placeholder, value in replacements.items():
        rendered = rendered.replace(placeholder, value)

    if "{{" in rendered or "${BIFROST_IMAGE" in rendered:
        print("error: unresolved placeholders remain in the production manifest", file=sys.stderr)
        return 1

    output_dir = (root / args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "compose.yaml").write_text(rendered, encoding="utf-8")
    (output_dir / "README.md").write_text(PRODUCTION_README, encoding="utf-8")
    release = {
        "distribution_version": args.version,
        "image": args.image,
        "digest": replacements["{{DIGEST}}"],
        "upstream_tag": args.upstream_tag,
        "upstream_commit": args.upstream_commit,
        "rendered_at": replacements["{{RELEASED_AT}}"],
    }
    (output_dir / "release.json").write_text(
        json.dumps(release, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(f"Rendered {output_dir / 'compose.yaml'}")
    print(f"Image: {args.image}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
