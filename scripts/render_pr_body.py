#!/usr/bin/env python3
"""Render the pull-request body for an automated upstream synchronization."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    lock = json.loads((root / "vendor.lock.json").read_text(encoding="utf-8"))
    upstream = lock["upstream"]
    vendor = lock["vendor"]
    distribution = lock["distribution"]

    stat = subprocess.run(
        ["git", "diff", "--stat", "origin/main...HEAD"],
        cwd=root,
        check=False,
        capture_output=True,
        text=True,
    ).stdout.strip()
    stat_lines = "\n".join(stat.splitlines()[-80:]) or "No path summary available."
    excluded = ", ".join(f"`{item}`" for item in vendor["excluded"])

    print(f"""## Automated upstream synchronization

| | |
|---|---|
| Upstream release | [{upstream['tag']}]({upstream['release_url']}) |
| Upstream commit | `{upstream['commit']}` |
| Upstream tree | `{upstream['git_tree']}` |
| Vendored files | {vendor['file_count']} |
| Vendored tree SHA-256 | `{vendor['tree_sha256']}` |
| Distribution revision | {distribution['revision']} |

This pull request was generated by `.github/workflows/sync-upstream.yml`.
It vendors the upstream gateway source under `upstream/` and refreshes
`vendor.lock.json` and `versions.env`.

**Merge gate:** CI must pass before this pull request can merge. A failed
build, smoke test, or vulnerability scan leaves the pull request open and the
production branch untouched.

<details>
<summary>Changed paths</summary>

```text
{stat_lines}
```

</details>

The following upstream paths are intentionally excluded from the mirror:
{excluded}.

Upstream release notes: {upstream['release_url']}
""")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
